// lib/core/constants/app_icons.dart

/// Standard icon sizes across Pulsr design system.
abstract final class AppIconSize {
  /// Extra small icon size (14px) - inline badges, trailing chips, micro hints.
  static const double xs = 14.0;

  /// Small icon size (18px) - auxiliary buttons, dense list items, indicators.
  static const double sm = 18.0;

  /// Medium icon size (22px) - standard list tiles, actions, bottom bar items.
  static const double md = 22.0;

  /// Large icon size (28px) - primary player controls, category headers.
  static const double lg = 28.0;

  /// Extra large icon size (36px) - hero cards, play/pause hubs, empty states.
  static const double xl = 36.0;
}
