"""Generate the offline Dart catalog without modifying Tanzil verse text.

Usage: python tools/generate_quran_text.py
Source and license: assets/quran/README.md
"""
from pathlib import Path
import hashlib
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'assets/quran/uthmani.xml'
raw = source.read_bytes()
expected_hash = '8c5aeae20363a98f6963720d29fce040ca8b56a8e75f8b564c257fce7f6d0417'
assert hashlib.sha256(raw).hexdigest() == expected_hash, 'Source checksum changed'
text = raw.decode('utf-8')
license_text = text.split('<!--', 1)[1].split('-->', 1)[0].strip()
surahs = ET.fromstring(raw).findall('sura')
assert len(surahs) == 114
assert sum(len(s.findall('aya')) for s in surahs) == 6236
lines = [
    '// GENERATED by tools/generate_quran_text.py. Do not edit verse text.',
    '// Source: https://tanzil.net/download/ (Uthmani 1.1).',
    '// The copyright notice below applies to all text in this file.',
    "const tanzilCopyrightNotice = r'''", license_text, "''';", '',
    'const quranUthmaniText = <int, List<String>>{',
]
for number, surah in enumerate(surahs, 1):
    assert int(surah.attrib['index']) == number
    lines.append(f'  {number}: [')
    for ayah_number, ayah in enumerate(surah.findall('aya'), 1):
        assert int(ayah.attrib['index']) == ayah_number
        verse = ayah.attrib['text']
        assert '$' not in verse
        lines.append(f'    {json.dumps(verse, ensure_ascii=False)},')
    lines.append('  ],')
lines.append('};')
output = ROOT / 'lib/data/quran/quran_uthmani_text.dart'
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print('Generated 114 surahs / 6236 unchanged Arabic verses.')
